const POSE_GRID: Record<Pose, string[]> = {
  idle: BASE_IDLE,
  pay: BASE_PAY,
  blocked: BASE_BLOCKED,
  readLedger: BASE_IDLE,
};

export function drawCharacter(
  ctx: CanvasRenderingContext2D,
  castId: keyof typeof CAST,
  pose: Pose,
  x: number,
  y: number,
  scale: number,
): void {
  const palette = CAST[castId]!;
  const grid = POSE_GRID[pose];
  for (let row = 0; row < grid.length; row++) {
    const line = grid[row] ?? '';
    for (let col = 0; col < line.length; col++) {
      const ch = line[col] ?? '.';
      const key = PALETTE_MAP[ch] ?? 'transparent';
      if (key === 'transparent') continue;
      ctx.fillStyle = palette[key];
      ctx.fillRect(x + col * scale, y + row * scale, scale, scale);
    }
  }
}

export function spriteDimensions(scale: number): { w: number; h: number } {
  return { w: 16 * scale, h: 22 * scale };
}
