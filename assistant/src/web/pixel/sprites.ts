const PALETTE_MAP: Record<string, keyof CharacterPalette | 'transparent'> = {
  '.': 'transparent',
  H: 'hair',
  S: 'skin',
  K: 'suit',
  W: 'shirt',
  B: 'shoes',
  T: 'tie',
};

